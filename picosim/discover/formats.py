"""
The discovery agent's memory layout and record formats, declared once.

agent.s never spells an offset or an address itself: build.py turns this
file into the agent's layout.inc (.equ lines), so the host and the agent can
never disagree about where a field is.

Everything is little-endian 32-bit words.

    batch header   at BATCH, HEADER words, written by the host
    case records   CASE_SIZE bytes each, at header.cases
    code blobs     anywhere in the batch area; a case points at its own
    results        RESULT_SIZE bytes each, written by the agent at header.results
    agent vars     at VARS: where the agent is (state, index) and the batch
                   footer (checksums, guard and sled checks)
"""

import struct

FORMAT_VERSION = 1
MAGIC = 0x42445350                  # 'PSDB'

# ── memory layouts ──────────────────────────────────────────────────────────
# hi: the agent in SRAM5 and its stacks in SRAM4 (most campaigns).
# lo: the agent at the start of SRAM, so SRAM4/5 are free to probe and to run
#     code in (campaigns A and D).
SHARED = {
    'SLED': 0x20010000, 'SLED_SIZE': 0x8000, 'SLOT': 0x20014000,
    'SCRATCH': 0x20018000, 'SCRATCH_MAX': 0x1000,
    'GUARD': 0x20019000, 'GUARD_SIZE': 0x1000,
    'RESULTS': 0x2001A000, 'RESULTS_END': 0x20040000,
}
LAYOUTS = {
    'hi': {**SHARED,
           'BATCH': 0x20000000, 'BATCH_END': 0x20010000,
           'MSP_TOP': 0x20040800, 'PSP_LO': 0x20040800, 'PSP_HI': 0x20041000, 'PSP_DEFAULT': 0x20040F00,
           'AGENT': 0x20041000, 'AGENT_SIZE': 0xF00, 'VARS': 0x20041F00},
    'lo': {**SHARED,
           'BATCH': 0x20002000, 'BATCH_END': 0x20010000,
           'MSP_TOP': 0x20001800, 'PSP_LO': 0x20001800, 'PSP_HI': 0x20002000, 'PSP_DEFAULT': 0x20001F00,
           'AGENT': 0x20000000, 'AGENT_SIZE': 0xF00, 'VARS': 0x20000F00},
}

SLED_FILL = 0xDE00DE00              # UDF #0 twice
SLED_HALF = 0xDE00
PATTERN_STEP = 0x9E3779B9           # scratch word i = seed + i * step
GUARD_KEY = 0xA5C3965A              # guard word at a = a ^ key
EXC_RETURN_PSP = 0xFFFFFFFD
EXC_RETURN_MSP = 0xFFFFFFF9

# ── batch header ────────────────────────────────────────────────────────────
HEADER = ['magic', 'version', 'n_cases', 'start', 'cases', 'results', 'scratch', 'scratch_words',
          'flags', 'guard', 'guard_words', 'sled', 'sled_words', 'sled_fill', 'wd_reload', 'reserved']
HEADER_SIZE = 4 * len(HEADER)
HF_NO_SCRATCH = 1                   # don't set or check the scratch window
HF_SYSTICK = 2                      # before every case: SysTick restarted from 0xFFFFFF, processor clock
HF_WATCHDOG = 4                     # ... from wd_reload with its interrupt on: a case that never ends is
                                    # stopped by SysTick (a result with ipsr 15)
HF_KEEP_SCRATCH = 8                 # set the scratch pattern but don't check or restore it (the host
                                    # reads the whole window: a case that changed more than MAX_INLINE)

# ── case record ─────────────────────────────────────────────────────────────
CASE = (['id', 'kind', 'code', 'code_len', 'slot']
        + [f'r{i}' for i in range(13)]
        + ['lr', 'psp', 'xpsr', 'primask', 'control', 'seed'])
CASE_SIZE = 4 * len(CASE)
KINDS = {'behaviour': 1, 'timing': 2, 'probe-read': 3, 'probe-write': 4, 'scenario': 5}

# ── result record ───────────────────────────────────────────────────────────
RESULT = (['id', 'ipsr']
          + ['f_r0', 'f_r1', 'f_r2', 'f_r3', 'f_r12', 'f_lr', 'f_pc', 'f_xpsr']
          + [f'r{i}' for i in range(4, 12)]
          + ['msp', 'psp', 'exc_return', 'primask', 'control', 'systick', 'n_changed',
             'off01', 'off23', 'val0', 'val1', 'val2', 'val3', 'frame'])
RESULT_SIZE = 4 * len(RESULT)
NOT_CHECKED = 0xFFFFFFFF            # n_changed when the scratch window was not checked
MAX_INLINE = 4                      # changed scratch words kept in a result

# ── agent variables and the batch footer ───────────────────────────────────
VARS = ['state', 'index', 'resptr', 'case', 'seed', 'filled', 'sum', 'sled_bad', 'sled_first',
        'guard_bad', 'guard_first', 'fault_pc', 'fault_lr', 'fault_msp']
STATE_START, STATE_RUNNING, STATE_BUSY, STATE_DONE, STATE_AGENT_FAULT = 0, 1, 2, 3, 4
STATE_NAMES = {0: 'starting', 1: 'running a case', 2: 'between cases', 3: 'done', 4: 'agent fault'}
BKPT_DONE, BKPT_AGENT_FAULT = 0x7F, 0x7E

assert CASE_SIZE == 96 and RESULT_SIZE == 128 and HEADER_SIZE == 64

# core registers the agent uses
PPB = {'SYST_CSR': 0xE000E010, 'SYST_RVR': 0xE000E014, 'SYST_CVR': 0xE000E018,
       'VTOR_REG': 0xE000ED08, 'ICSR_REG': 0xE000ED04,
       'NVIC_ICER': 0xE000E180, 'NVIC_ICPR': 0xE000E280}


def offsets(fields):
    return {f: 4 * i for i, f in enumerate(fields)}


def layout_inc(layout='hi'):
    """The agent's layout.inc for one layout."""
    lines = [f"@ generated by picosim/discover/formats.py (format {FORMAT_VERSION}); do not edit"]
    for k, v in {**LAYOUTS[layout], **PPB}.items():
        lines.append(f".equ {k}, 0x{v:08X}")
    for k, v in (('SLED_HALF', SLED_HALF), ('PATTERN_STEP', PATTERN_STEP), ('GUARD_KEY', GUARD_KEY),
                 ('EXC_RETURN_PSP', EXC_RETURN_PSP), ('EXC_RETURN_MSP', EXC_RETURN_MSP),
                 ('HF_NO_SCRATCH', HF_NO_SCRATCH), ('HF_SYSTICK', HF_SYSTICK), ('HF_WATCHDOG', HF_WATCHDOG), ('HF_KEEP_SCRATCH', HF_KEEP_SCRATCH),
                 ('CASE_SIZE', CASE_SIZE), ('RESULT_SIZE', RESULT_SIZE),
                 ('BKPT_DONE', BKPT_DONE), ('BKPT_AGENT_FAULT', BKPT_AGENT_FAULT)):
        lines.append(f".equ {k}, 0x{v:X}")
    for prefix, fields in (('H_', HEADER), ('C_', CASE), ('R_', RESULT), ('V_', VARS)):
        for f, o in offsets(fields).items():
            lines.append(f".equ {prefix}{f.upper()}, {o}")
    for k in ('STATE_START', 'STATE_RUNNING', 'STATE_BUSY', 'STATE_DONE', 'STATE_AGENT_FAULT'):
        lines.append(f".equ {k}, {globals()[k]}")
    return '\n'.join(lines) + '\n'


# ── packing and unpacking ──────────────────────────────────────────────────

def pack_words(fields, values):
    return struct.pack(f'<{len(fields)}I', *[values.get(f, 0) & 0xFFFFFFFF for f in fields])


def unpack_words(fields, data):
    return dict(zip(fields, struct.unpack(f'<{len(fields)}I', data[:4 * len(fields)])))


def pack_case(c):
    return pack_words(CASE, c)


def unpack_result(data):
    """A result record as a dict, with the changed scratch words as
    'changed': [(offset, value)] (at most MAX_INLINE; 'overflow' says if
    there were more)."""
    r = unpack_words(RESULT, data)
    n = r['n_changed']
    if n == NOT_CHECKED:
        r['changed'], r['overflow'] = None, False
    else:
        offs = [r['off01'] & 0xFFFF, r['off01'] >> 16, r['off23'] & 0xFFFF, r['off23'] >> 16]
        vals = [r['val0'], r['val1'], r['val2'], r['val3']]
        k = min(n, MAX_INLINE)
        r['changed'] = list(zip(offs[:k], vals[:k]))
        r['overflow'] = n > MAX_INLINE
    return r


def pattern_word(seed, i):
    return (seed + i * PATTERN_STEP) & 0xFFFFFFFF


def pattern(seed, words):
    return struct.pack(f'<{words}I', *[pattern_word(seed, i) for i in range(words)])


def guard_bytes(addr, words):
    return struct.pack(f'<{words}I', *[(addr + 4 * i) ^ GUARD_KEY for i in range(words)])


def fnv32(data):
    """The agent's checksum: FNV-1 style over little-endian words."""
    h = 0x811C9DC5
    for (w,) in struct.iter_unpack('<I', data):
        h = ((h ^ w) * 0x01000193) & 0xFFFFFFFF
    return h
