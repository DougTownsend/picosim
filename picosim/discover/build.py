"""
Build the discovery agent (agent.s) for one memory layout, cached.

    a = build.agent('hi')     # an Agent: .image (bytes at .base), .symbols, .sha1

The layout's addresses and every record offset come from formats.py, written
into layout.inc and the linker script here, so they cannot drift apart.
"""

import hashlib
import os

from elftools.elf.elffile import ELFFile

from . import formats as F

LD = """/* generated by picosim/discover/build.py */
ENTRY(agent_start)
MEMORY {{ AGENT (rwx) : ORIGIN = 0x{base:08X}, LENGTH = 0x{size:X} }}
SECTIONS
{{
    . = 0x{base:08X};
    .vectors : {{ *(.vectors) }} > AGENT
    .text : {{ *(.text*) *(.rodata*) }} > AGENT
    .data : {{ *(.data*) *(.bss*) *(COMMON) }} > AGENT
}}
"""


class BuildError(Exception):
    pass


def _here():
    return os.path.dirname(os.path.abspath(__file__))


def cache_dir(*parts):
    try:
        from platformdirs import user_cache_dir
        d = os.path.join(user_cache_dir("picosim"), "discover", *parts)
    except ImportError:
        d = os.path.join(os.path.expanduser("~/.cache/picosim/discover"), *parts)
    os.makedirs(d, exist_ok=True)
    return d


class Agent:
    def __init__(self, layout, image, base, symbols, elf):
        self.layout = layout
        self.lay = F.LAYOUTS[layout]
        self.image = image
        self.base = base
        self.symbols = symbols
        self.elf = elf
        self.sha1 = hashlib.sha1(image).hexdigest()

    @property
    def checksum(self):
        """What the agent's own checksum (V_SUM) must read."""
        n = self.symbols['agent_end'] - self.base
        return F.fnv32(self.image[:n])


def _write_if_changed(path, text):
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old != text:
        tmp = f"{path}.{os.getpid()}.tmp"
        with open(tmp, 'w') as f:
            f.write(text)
        os.replace(tmp, path)


_cache = {}


def agent(layout='hi'):
    from ..sim import assemble
    lay = F.LAYOUTS[layout]
    d = cache_dir('agent', layout)
    inc, ld = F.layout_inc(layout), LD.format(base=lay['AGENT'], size=lay['AGENT_SIZE'])
    src = os.path.join(_here(), 'agent.s')
    with open(src) as f:
        key = hashlib.sha1((f.read() + inc + ld).encode()).hexdigest()[:12]
    if (layout, key) in _cache:
        return _cache[(layout, key)]
    _write_if_changed(os.path.join(d, 'layout.inc'), inc)
    _write_if_changed(os.path.join(d, 'agent.ld'), ld)
    elf = os.path.join(d, f'agent-{key}.elf')
    if not os.path.exists(elf):
        ok, msg = assemble(src, elf, os.path.join(d, 'agent.ld'), extra_ld_flags=[f'-Wa,-I{d}'])
        if not ok:
            raise BuildError(f"building the discovery agent ({layout}) failed:\n{msg}")
    image = bytearray()
    syms = {}
    with open(elf, 'rb') as f:
        e = ELFFile(f)
        for seg in e.iter_segments():
            if seg.header.p_type != 'PT_LOAD' or not seg.header.p_memsz:
                continue
            off = seg.header.p_vaddr - lay['AGENT']
            data = seg.data()
            if off < 0 or off + seg.header.p_memsz > lay['AGENT_SIZE']:
                raise BuildError(f"the agent does not fit in 0x{lay['AGENT_SIZE']:X} bytes")
            if len(image) < off + len(data):
                image.extend(bytes(off + len(data) - len(image)))
            image[off:off + len(data)] = data
        for s in e.get_section_by_name('.symtab').iter_symbols():
            if s.name and not s.name.startswith('$') and s['st_shndx'] != 'SHN_ABS':
                syms[s.name] = s['st_value'] & ~1 if s['st_info']['type'] == 'STT_FUNC' else s['st_value']
    while len(image) % 4:
        image.append(0)
    a = Agent(layout, bytes(image), lay['AGENT'], syms, elf)
    if a.symbols['vectors'] != lay['AGENT'] or a.symbols['vectors'] % 256:
        raise BuildError("the agent's vector table is not at the start of its area, 256-byte aligned")
    _cache[(layout, key)] = a
    return a
